import AppKit

/// Watches the general pasteboard, keeps a persistent MRU history and
/// enforces a 30 MB budget. The most recent entries stay first; pinned entries
/// survive eviction as long as possible.
final class ClipboardHistoryStore {
    static let shared = ClipboardHistoryStore()

    static let maxBytes = 30 * 1024 * 1024

    private(set) var entries: [ClipboardEntry] = []
    private(set) var totalBytes = 0

    private var timer: Timer?
    private var lastChangeCount = 0
    private var started = false
    private let ioQueue = DispatchQueue(label: "com.henri.CSL.clipboard", qos: .utility)
    private var imageCache: [UUID: NSImage] = [:]

    private let consumedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    private init() {
        AppPaths.prepareClipboard()
        load()
    }

    // MARK: - Lifecycle

    func start() {
        guard !started else { return }
        started = true
        AppPaths.prepareClipboard()
        lastChangeCount = NSPasteboard.general.changeCount
        captureCurrent()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.debug("clipboard history started: \(entries.count) entries, \(totalBytes) bytes")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        started = false
    }

    func flush() {
        ioQueue.sync {}
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        capture(pasteboard)
    }

    func captureCurrent() {
        let pasteboard = NSPasteboard.general
        lastChangeCount = pasteboard.changeCount
        capture(pasteboard)
    }

    // MARK: - Capture

    private func capture(_ pasteboard: NSPasteboard) {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: consumedTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            let payload = Data(paths.joined(separator: "\u{0}").utf8)
            add(
                kind: .files,
                fingerprint: fingerprint(.files, payload),
                text: nil,
                filePaths: paths,
                imageData: nil,
                imageSize: nil,
                byteSize: payload.count + 64,
                sourceApp: source
            )
            return
        }

        if let image = NSImage(pasteboard: pasteboard) {
            if let tiff = image.tiffRepresentation,
               let rep = NSBitmapImageRep(data: tiff),
               let png = rep.representation(using: .png, properties: [:]) {
                add(
                    kind: .image,
                    fingerprint: fingerprint(.image, png),
                    text: nil,
                    filePaths: nil,
                    imageData: png,
                    imageSize: (rep.pixelsWide, rep.pixelsHigh),
                    byteSize: png.count + 64,
                    sourceApp: source
                )
                return
            }
        }

        guard let raw = pasteboard.string(forType: .string) else { return }
        let text = raw.replacingOccurrences(of: "\u{0}", with: "")
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let data = Data(text.utf8)
        guard data.count + 64 <= Self.maxBytes else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = URL(string: trimmed)?.scheme?.lowercased().hasPrefix("http") == true
            && !trimmed.contains(where: \.isWhitespace)
        add(
            kind: isLink ? .link : .text,
            fingerprint: fingerprint(isLink ? .link : .text, data),
            text: text,
            filePaths: nil,
            imageData: nil,
            imageSize: nil,
            byteSize: data.count + 64,
            sourceApp: source
        )
    }

    private func fingerprint(_ kind: ClipboardEntryKind, _ payload: Data) -> String {
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in payload {
            hash ^= UInt64(byte)
            hash &*= 0x0000_0100_0000_01b3
        }
        return "\(kind.rawValue)-\(String(hash, radix: 16))-\(payload.count)"
    }

    private func add(
        kind: ClipboardEntryKind,
        fingerprint: String,
        text: String?,
        filePaths: [String]?,
        imageData: Data?,
        imageSize: (Int, Int)?,
        byteSize: Int,
        sourceApp: String?
    ) {
        guard byteSize <= Self.maxBytes else { return }
        let id = UUID()
        var blobName: String?

        if let imageData {
            blobName = id.uuidString + ".png"
            imageCache[id] = NSImage(data: imageData)
            let url = AppPaths.clipboardBlobsDirectory.appendingPathComponent(blobName!)
            ioQueue.async {
                try? imageData.write(to: url, options: .atomic)
            }
        }

        var pinned = false
        if let existing = entries.firstIndex(where: { $0.fingerprint == fingerprint }) {
            pinned = entries[existing].pinned
            let old = entries.remove(at: existing)
            totalBytes -= old.byteSize
            removeBlob(old)
            if old.id != id {
                imageCache.removeValue(forKey: old.id)
            }
        }

        let entry = ClipboardEntry(
            id: id,
            kind: kind,
            createdAt: Date(),
            fingerprint: fingerprint,
            pinned: pinned,
            text: text,
            filePaths: filePaths,
            blobName: blobName,
            byteSize: byteSize,
            sourceApp: sourceApp,
            imageWidth: imageSize?.0,
            imageHeight: imageSize?.1
        )
        entries.insert(entry, at: 0)
        totalBytes += byteSize
        enforceLimit()
        save()
        notifyChanged()
    }

    // MARK: - Public history actions

    func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].pinned.toggle()
        save()
        notifyChanged()
    }

    func delete(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        let entry = entries.remove(at: index)
        totalBytes -= entry.byteSize
        imageCache.removeValue(forKey: entry.id)
        removeBlob(entry)
        save()
        notifyChanged()
    }

    func clear() {
        let old = entries
        entries.removeAll()
        totalBytes = 0
        imageCache.removeAll()
        ioQueue.async {
            for entry in old { self.removeBlobNow(entry) }
        }
        save()
        notifyChanged()
    }

    // MARK: - Copy

    @discardableResult
    func copy(_ entry: ClipboardEntry) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        var ok = true

        switch entry.kind {
        case .text, .link:
            if let text = entry.text {
                ok = pasteboard.setString(text, forType: .string)
            }
        case .image:
            if let data = imageData(for: entry) {
                ok = pasteboard.setData(data, forType: .png)
            } else {
                ok = false
            }
        case .files:
            let urls = (entry.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            ok = pasteboard.writeObjects(urls)
        }

        if ok {
            lastChangeCount = pasteboard.changeCount
            if let index = entries.firstIndex(where: { $0.id == entry.id }) {
                var moved = entries.remove(at: index)
                moved.createdAt = Date()
                entries.insert(moved, at: 0)
                save()
                notifyChanged()
            }
        }
        return ok
    }

    // MARK: - Queries

    func filtered(_ query: String) -> [ClipboardEntry] {
        let needle = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !needle.isEmpty else { return entries }
        return entries.filter { $0.searchText.contains(needle) }
    }

    func image(for entry: ClipboardEntry) -> NSImage? {
        if let cached = imageCache[entry.id] { return cached }
        guard let url = entry.imageURL,
              let image = NSImage(contentsOf: url) else { return nil }
        imageCache[entry.id] = image
        return image
    }

    func imageData(for entry: ClipboardEntry) -> Data? {
        guard let url = entry.imageURL else { return nil }
        return try? Data(contentsOf: url)
    }

    var capacity: Int { Self.maxBytes }

    // MARK: - Persistence

    private func load() {
        AppPaths.prepareClipboard()
        guard let data = try? Data(contentsOf: AppPaths.clipboardIndexFile),
              let decoded = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else {
            entries = []
            totalBytes = 0
            return
        }
        entries = decoded
            .filter { entry in
                if entry.kind == .image {
                    return entry.imageURL.map { FileManager.default.fileExists(atPath: $0.path) } ?? false
                }
                return true
            }
            .sorted { $0.createdAt > $1.createdAt }
        totalBytes = entries.reduce(0) { $0 + $1.byteSize }
        enforceLimit()
    }

    private func save() {
        let snapshot = entries
        ioQueue.async {
            do {
                let data = try JSONEncoder().encode(snapshot)
                try data.write(to: AppPaths.clipboardIndexFile, options: .atomic)
            } catch {
                Log.debug("clipboard history save failed: \(error)")
            }
        }
    }

    private func enforceLimit() {
        while totalBytes > Self.maxBytes, !entries.isEmpty {
            let index: Int
            if let oldestUnpinned = entries.lastIndex(where: { !$0.pinned }) {
                index = oldestUnpinned
            } else {
                index = entries.count - 1
            }
            let entry = entries.remove(at: index)
            totalBytes -= entry.byteSize
            imageCache.removeValue(forKey: entry.id)
            removeBlob(entry)
        }
    }

    private func removeBlob(_ entry: ClipboardEntry) {
        ioQueue.async { self.removeBlobNow(entry) }
    }

    private func removeBlobNow(_ entry: ClipboardEntry) {
        guard let url = entry.imageURL else { return }
        try? FileManager.default.removeItem(at: url)
    }

    private func notifyChanged() {
        NotificationCenter.default.post(name: .cslClipboardChanged, object: self)
    }
}
